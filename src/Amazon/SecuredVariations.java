package Amazon;
import java.util.*;

public class SecuredVariations {

    private static final int MOD = (int) 1e9 + 7;

    
    // Recursive Approach with Memoization (not DP)
    public static int countSecuredStrings(String s, String t) {
        int m = s.length(); // Length of s
        int n = t.length(); // Length of t

        // Edge case: If t is empty, all subsequences of s are valid
        if (n == 0) return (int) Math.pow(2, m) % MOD;

        // Create a memoization table initialized with -1
        Integer[][] memo = new Integer[m][n];

        // Start the recursive computation
        return countSecuredStringsHelper(s, t, 0, 0, memo);
    }

    private static int countSecuredStringsHelper(String s, String t, int i, int j, Integer[][] memo) {
        // Base case: If t is fully matched, all remaining subsequences of s are valid
        if (j == t.length()) return (int) Math.pow(2, s.length() - i) % MOD;

        // Base case: If s is exhausted, no valid subsequences exist
        if (i == s.length()) return 0;

        // Check if the result is already computed
        if (memo[i][j] != null) return memo[i][j];

        int result = 0;

        // Option 1: Exclude s[i]
        result = (result + countSecuredStringsHelper(s, t, i + 1, j, memo)) % MOD;

        // Option 2: Include s[i]
        if (s.charAt(i) > t.charAt(j)) {
            // All subsequences formed by including s[i] are valid
            result = (result + (int) Math.pow(2, s.length() - i - 1)) % MOD;
        } else if (s.charAt(i) == t.charAt(j)) {
            // Continue comparing the next characters
            result = (result + countSecuredStringsHelper(s, t, i + 1, j + 1, memo)) % MOD;
        }

        // Store the result in the memoization table
        return memo[i][j] = result;
    }

    public static void main(String[] args) {
        // Test cases
        List<String[]> testCases = Arrays.asList(
            new String[]{"aba", "ab"}, // Example 1: Output = 3
            new String[]{"bab", "ab"}, // Example 2: Output = 5
            new String[]{"abc", ""},  // Edge case: t is empty -> Output = 7 (2^3)
            new String[]{"a", "b"},   // Edge case: No valid subsequences -> Output = 0
            new String[]{"b", "a"},   // Edge case: All subsequences are valid -> Output = 1
            new String[]{"aaa", "a"}, // Edge case: Many duplicates -> Output = 3
            new String[]{"zzz", "z"}  // Edge case: Large lexicographical difference -> Output = 7
        );

        for (String[] testCase : testCases) {
            String s = testCase[0];
            String t = testCase[1];
            System.out.println("s = " + s + ", t = " + t + " => Result = " + countSecuredStrings(s, t));
        }
    }
}


